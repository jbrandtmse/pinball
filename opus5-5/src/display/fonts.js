function glyphsFromRows(src, w, h) {
  const out = {};
  for (const ch in src) {
    const bits = src[ch];
    const rows = [];
    for (let y = 0; y < h; y++) rows.push(bits.slice(y * w, y * w + w).replace(/1/g, '#').replace(/0/g, '.'));
    out[ch] = { w, rows };
  }
  return out;
}

