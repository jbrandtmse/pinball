function glyphsFromColumns(table, h) {
  const out = {};
  for (const ch in table) {
    const cols = table[ch];
    // trim empty leading/trailing columns for proportional spacing (keep space wide)
    let a = 0, b = cols.length - 1;
    if (ch !== ' ') { while (a < b && cols[a] === 0) a++; while (b > a && cols[b] === 0) b--; }
    else { a = 0; b = 2; }
    const w = b - a + 1;
    const rows = [];
    for (let y = 0; y < h; y++) {
      let r = '';
      for (let x = a; x <= b; x++) r += (cols[x] >> y) & 1 ? '#' : '.';
      rows.push(r);
    }
    out[ch] = { w, rows };
  }
  return out;
}

