  function compile(map, w, h) {
    var out = {};
    for (var ch in map) {
      var rows = map[ch].split(' ');
      var glyph = { w: w, h: h, rows: [] };
      for (var y = 0; y < h; y++) {
        var bits = 0, r = rows[y] || '';
        for (var x = 0; x < w; x++) if (r[x] === '#') bits |= (1 << x);
        glyph.rows.push(bits);
      }
      out[ch] = glyph;
    }
    return out;
  }

